def device_dicts(hass: HomeAssistant) -> list[dict[str, Any]]:
    """The current device list in the card's shape, as the websocket sends it."""
    entry = hass.config_entries.async_loaded_entries(DOMAIN)[0]
    return [device.to_dict() for device in entry.runtime_data.data.devices]


def device_dict(hass: HomeAssistant, name: str) -> dict[str, Any]:
    """One device by display name."""
    for device in device_dicts(hass):
        if device["name"] == name:
            return device
    raise AssertionError(f"no device named {name}")


async def load_fixture_into_hass(hass: HomeAssistant, snapshot: dict[str, Any]) -> dict[str, str]:
    """Recreate the JSON fixture inside a live test instance.

    Areas, devices and entities go into the real registries and every
    state is set with its original timestamp, so the integration sees
    exactly what the card's fixture describes. Device ids are generated by
    Home Assistant; the returned map goes from fixture id to real id.
    """
    area_registry = ar.async_get(hass)
    device_registry = dr.async_get(hass)
    entity_registry = er.async_get(hass)

    # Devices must belong to a config entry; a throwaway one will do.
    owner = MockConfigEntry(domain="test_fixture", title="Fixture")
    owner.add_to_hass(hass)

    for area in snapshot["areas"].values():
        created = area_registry.async_get_or_create(area["name"])
        assert created.id == area["area_id"], "area id must match the fixture's"

    device_ids: dict[str, str] = {}
    for device in snapshot["devices"].values():
        created_device = device_registry.async_get_or_create(
            config_entry_id=owner.entry_id,
            identifiers={("test_fixture", device["id"])},
            name=device["name"],
            manufacturer=device["manufacturer"],
            model=device["model"],
            entry_type=dr.DeviceEntryType.SERVICE if device["entry_type"] == "service" else None,
        )
        device_registry.async_update_device(
            created_device.id,
            area_id=device["area_id"],
            name_by_user=device["name_by_user"],
            disabled_by=dr.DeviceEntryDisabler.USER if device["disabled_by"] else None,
        )
        device_ids[device["id"]] = created_device.id

    for entity in snapshot["entities"].values():
        domain, object_id = entity["entity_id"].split(".", 1)
        category = entity.get("entity_category")
        created_entity = entity_registry.async_get_or_create(
            domain,
            entity["platform"],
            entity["entity_id"],
            suggested_object_id=object_id,
            device_id=device_ids.get(entity.get("device_id", "")),
            entity_category=EntityCategory(category) if category else None,
        )
        assert created_entity.entity_id == entity["entity_id"]

    for state in snapshot["states"].values():
        moment = datetime.fromisoformat(state["last_updated"])
        hass.states.async_set(
            state["entity_id"], state["state"], state["attributes"], timestamp=moment.timestamp()
        )
    await hass.async_block_till_done()
    return device_ids


async def open_general_options(hass: HomeAssistant, entry_id: str) -> ConfigFlowResult:
    """Open Configure and choose its general options (thresholds, filters...)."""
    result = await hass.config_entries.options.async_init(entry_id)
    return await hass.config_entries.options.async_configure(
        result["flow_id"], {"next_step_id": "general"}
    )


def sent_messages(calls: list[ServiceCall]) -> list[str]:
    return [call.data["message"] for call in calls]


async def advance(hass: HomeAssistant, freezer: FrozenDateTimeFactory, delta: timedelta) -> None:
    """Advance time and let timers, the debounced refresh and the notifier run.

    The notifier reacts to each refresh in a background task, which
    `async_block_till_done` skips unless asked. Without waiting for it, a
    slow machine (CI under load) checks for messages before they are sent.
    """
    freezer.tick(delta)
    async_fire_time_changed(hass)
    await hass.async_block_till_done(wait_background_tasks=True)


async def set_up_notify(
    hass: HomeAssistant,
    fixture_snapshot: dict[str, Any],
    freezer: FrozenDateTimeFactory,
    fixed_now: datetime,
    options: dict[str, Any] | None = None,
) -> tuple[MockConfigEntry, dict[str, str], list[ServiceCall]]:
    freezer.move_to(fixed_now)
    calls = async_mock_service(hass, "notify", "mobile_app_test")
    device_ids = await load_fixture_into_hass(hass, fixture_snapshot)
    entry = MockConfigEntry(
        domain=DOMAIN, title="Pulse Check", unique_id=DOMAIN, options=options or NOTIFY_OPTIONS
    )
    entry.add_to_hass(hass)
    assert await hass.config_entries.async_setup(entry.entry_id)
    await hass.async_block_till_done(wait_background_tasks=True)
    return entry, device_ids, calls


async def past_grace(hass: HomeAssistant, freezer: FrozenDateTimeFactory) -> None:
    """Let the startup grace period pass; the baseline is recorded at its end."""
    await advance(hass, freezer, timedelta(minutes=DEFAULT_STARTUP_GRACE_MINUTES, seconds=1))


def local_time(day: int, hour: int, minute: int = 0) -> datetime:
    """A moment in October 2026 on the test instance's local clock."""
    return datetime(2026, 10, day, hour, minute, tzinfo=dt_util.get_default_time_zone())


def digest_messages(calls: list[ServiceCall], kind: str) -> list[str]:
    return [m for m in sent_messages(calls) if m.startswith(f"Pulse Check {kind} digest")]


async def restart_ha(
    hass: HomeAssistant, entry: MockConfigEntry, freezer: FrozenDateTimeFactory, at: datetime
) -> None:
    """Home Assistant stops, stays off until `at`, then starts the entry again."""
    await advance(hass, freezer, timedelta(seconds=5))  # the store's save delay
    assert await hass.config_entries.async_unload(entry.entry_id)
    await hass.async_block_till_done(wait_background_tasks=True)
    # A new run of Home Assistant: what a reload keeps in memory is gone.
    hass.data.pop(DATA_RUNTIME, None)
    freezer.move_to(at)
    assert await hass.config_entries.async_setup(entry.entry_id)
    await hass.async_block_till_done(wait_background_tasks=True)


async def confirm_offline(hass: HomeAssistant, freezer: FrozenDateTimeFactory) -> None:
    """Let a new offline state be seen, then confirmed."""
    await advance(hass, freezer, timedelta(seconds=DEBOUNCE_SECONDS + 1))
    await advance(hass, freezer, timedelta(minutes=DEFAULT_CONFIRM_MINUTES + 1))


async def plug_offline(hass: HomeAssistant, freezer: FrozenDateTimeFactory) -> None:
    hass.states.async_set("switch.office_plug", "unavailable")
    hass.states.async_set("sensor.office_plug_power", "unavailable")
    await confirm_offline(hass, freezer)


async def ht_offline(hass: HomeAssistant, freezer: FrozenDateTimeFactory) -> None:
    hass.states.async_set("sensor.kitchen_ht_temperature", "unavailable")
    await confirm_offline(hass, freezer)


async def start_integration(
    hass: HomeAssistant,
    fixture_snapshot: dict[str, Any],
    freezer: FrozenDateTimeFactory,
    fixed_now: datetime,
    *,
    entry: MockConfigEntry | None = None,
    options: dict[str, Any] | None = None,
) -> tuple[MockConfigEntry, dict[str, str]]:
    """Freeze the clock, load the fixture and set Pulse Check up.

    Waits for background tasks too: setup starts a history refresh in one,
    which ends in a coordinator refresh. Without waiting, that refresh can
    land after the test's next step on a slow machine.
    """
    freezer.move_to(fixed_now)
    device_ids = await load_fixture_into_hass(hass, fixture_snapshot)
    if entry is None:
        entry = MockConfigEntry(
            domain=DOMAIN, title="Pulse Check", unique_id=DOMAIN, options=options or {}
        )
        entry.add_to_hass(hass)
    assert await hass.config_entries.async_setup(entry.entry_id)
    await hass.async_block_till_done(wait_background_tasks=True)
    return entry, device_ids

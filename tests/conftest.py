async def load_fixture_into_hass(hass: HomeAssistant, snapshot: dict[str, Any]) -> dict[str, str]:
    """Recreate the JSON fixture inside a live test instance.

    Areas, devices and entities go into the real registries and every
    state is set with its original timestamp, so the integration sees
    exactly what the card's fixture describes. Device ids are generated by
    Home Assistant; the returned map goes from fixture id to real id.
    """
    area_registry = ar.async_get(hass)
    device_registry = dr.async_get(hass)
    entity_registry = er.async_get(hass)

    # Devices must belong to a config entry; a throwaway one will do.
    owner = MockConfigEntry(domain="test_fixture", title="Fixture")
    owner.add_to_hass(hass)

    for area in snapshot["areas"].values():
        created = area_registry.async_get_or_create(area["name"])
        assert created.id == area["area_id"], "area id must match the fixture's"

    device_ids: dict[str, str] = {}
    for device in snapshot["devices"].values():
        created_device = device_registry.async_get_or_create(
            config_entry_id=owner.entry_id,
            identifiers={("test_fixture", device["id"])},
            name=device["name"],
            manufacturer=device["manufacturer"],
            model=device["model"],
            entry_type=dr.DeviceEntryType.SERVICE if device["entry_type"] == "service" else None,
        )
        device_registry.async_update_device(
            created_device.id,
            area_id=device["area_id"],
            name_by_user=device["name_by_user"],
            disabled_by=dr.DeviceEntryDisabler.USER if device["disabled_by"] else None,
        )
        device_ids[device["id"]] = created_device.id

    for entity in snapshot["entities"].values():
        domain, object_id = entity["entity_id"].split(".", 1)
        category = entity.get("entity_category")
        created_entity = entity_registry.async_get_or_create(
            domain,
            entity["platform"],
            entity["entity_id"],
            suggested_object_id=object_id,
            device_id=device_ids.get(entity.get("device_id", "")),
            entity_category=EntityCategory(category) if category else None,
        )
        assert created_entity.entity_id == entity["entity_id"]

    for state in snapshot["states"].values():
        moment = datetime.fromisoformat(state["last_updated"])
        hass.states.async_set(
            state["entity_id"], state["state"], state["attributes"], timestamp=moment.timestamp()
        )
    await hass.async_block_till_done()
    return device_ids
